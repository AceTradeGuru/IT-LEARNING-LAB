"""
Royal Grind — database access, SQLite locally and Postgres in production.

The app talks to one connection API. This module makes SQLite and Postgres both
answer to it, so `app.py` reads the same either way:

    conn.execute("SELECT * FROM reps WHERE org_id = ?", (org_id,)).fetchall()
    new_id = conn.execute("INSERT INTO reps (...) VALUES (?,?)", (...)).lastrowid

Three differences are papered over here, and nowhere else:

  1. **Placeholders.** SQLite uses `?`, Postgres uses `%s`.
  2. **New row ids.** SQLite exposes `cursor.lastrowid`; Postgres needs an explicit
     `RETURNING id`, which is appended automatically to INSERTs that lack one.
  3. **Upserts.** `INSERT OR IGNORE` becomes `ON CONFLICT DO NOTHING`.

Which engine is used depends solely on whether `DATABASE_URL` is set. There is no
flag to get wrong.

> **Testing status.** The SQLite path is exercised by the whole smoke suite. The
> Postgres path is written against the psycopg 3 API but has not been run against
> a live server — there is no Postgres on the development machine. Treat the first
> Render deploy as the real test of it, and run `python3 db.py --check` there.
"""

import os
import re

DATABASE_URL = os.environ.get("DATABASE_URL", "")
IS_POSTGRES = DATABASE_URL.startswith(("postgres://", "postgresql://"))


# ---------------------------------------------------------------- rewriting --

def _to_pg(sql):
    """
    Translate a SQLite statement into its Postgres equivalent.

    Only the constructs this codebase actually uses are handled. It is a narrow
    translator on purpose — a general SQL rewriter would be a source of subtle
    bugs, and every query here is one we wrote.
    """
    # INSERT OR IGNORE -> ON CONFLICT DO NOTHING. Applied before placeholders so
    # the trailing clause lands after any RETURNING handling below.
    ignore = False
    if re.match(r"\s*INSERT\s+OR\s+IGNORE\s+INTO", sql, re.I):
        ignore = True
        sql = re.sub(r"(\s*)INSERT\s+OR\s+IGNORE\s+INTO", r"\1INSERT INTO", sql, count=1,
                     flags=re.I)

    # Placeholders. None of our SQL contains a literal '?' inside a string, so a
    # straight replacement is safe here; it would not be in general.
    sql = sql.replace("?", "%s")

    if ignore:
        sql = sql.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    return sql


def _needs_returning(sql):
    return (re.match(r"\s*INSERT\s+INTO", sql, re.I)
            and not re.search(r"\bRETURNING\b", sql, re.I))


def translate_schema(sql):
    """
    Convert the SQLite schema DDL to Postgres.

    Kept as a transformation rather than a second hand-maintained schema file:
    two schemas drift, and the drift is silent until a column is missing in
    production.
    """
    out = []
    for stmt in sql.split(";"):
        s = stmt.strip()
        # Leading `--` comment lines sit in front of the first statement, so the
        # PRAGMA check has to look past them rather than at the raw prefix.
        body = "\n".join(l for l in s.splitlines() if not l.strip().startswith("--")).strip()
        if not body or body.upper().startswith("PRAGMA"):
            continue
        s = re.sub(r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT",
                   "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", s, flags=re.I)
        s = re.sub(r"\bREAL\b", "DOUBLE PRECISION", s, flags=re.I)
        # SQLite stores booleans as 0/1 INTEGERs; Postgres accepts that for
        # smallint columns, so is_mandatory etc. keep working unchanged.
        s = re.sub(r"DROP TABLE IF EXISTS (\w+)", r"DROP TABLE IF EXISTS \1 CASCADE", s,
                   flags=re.I)
        out.append(s)
    return ";\n".join(out) + ";"


# -------------------------------------------------------------- connections --

class _PGCursor:
    """Wraps a psycopg cursor so it answers like a sqlite3 one."""

    def __init__(self, cur, lastrowid=None):
        self._cur = cur
        self.lastrowid = lastrowid

    def fetchone(self):
        return self._cur.fetchone()

    def fetchall(self):
        return self._cur.fetchall()

    def __iter__(self):
        return iter(self._cur)


class _PGConnection:
    """A psycopg connection presenting the sqlite3 surface the app expects."""

    def __init__(self, raw):
        self._raw = raw

    def execute(self, sql, params=()):
        translated = _to_pg(sql)
        returning = _needs_returning(sql)
        if returning:
            translated = translated.rstrip().rstrip(";") + " RETURNING id"
        cur = self._raw.cursor()
        cur.execute(translated, params)
        last = None
        if returning:
            row = cur.fetchone()
            # An ON CONFLICT DO NOTHING that conflicted returns no row. None is
            # the honest answer there, and callers of INSERT OR IGNORE ignore it.
            last = (row["id"] if row else None)
        return _PGCursor(cur, last)

    def executescript(self, sql):
        with self._raw.cursor() as cur:
            cur.execute(translate_schema(sql))
        self._raw.commit()

    def commit(self):
        self._raw.commit()

    def rollback(self):
        self._raw.rollback()

    def close(self):
        self._raw.close()


def connect(sqlite_path=None):
    """
    Open a connection to whichever engine is configured.

    Rows come back mapping-style from both engines, so `row["name"]` works
    everywhere and the templates never learn which database they are on.
    """
    if IS_POSTGRES:
        import psycopg
        from psycopg.rows import dict_row
        raw = psycopg.connect(DATABASE_URL, row_factory=dict_row, autocommit=False)
        return _PGConnection(raw)

    import sqlite3
    conn = sqlite3.connect(sqlite_path)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    # Write-ahead logging lets reads proceed during a write. It does not make
    # SQLite safe for real concurrency — it makes local development less annoying.
    conn.execute("PRAGMA journal_mode = WAL")
    return conn


def engine_name():
    return "postgres" if IS_POSTGRES else "sqlite"


if __name__ == "__main__":
    import sys
    if "--check" in sys.argv:
        # Run this once on the first Render deploy to confirm the Postgres path.
        print(f"engine: {engine_name()}")
        if not IS_POSTGRES:
            print("DATABASE_URL is not set — nothing to check.")
            raise SystemExit(0)
        c = connect()
        row = c.execute("SELECT COUNT(*) AS n FROM orgs").fetchone()
        print(f"orgs: {row['n']}")
        rid = c.execute(
            "INSERT INTO orgs (name, slug, plan, status, created_at) VALUES (?,?,?,?,?)",
            ("__selfcheck__", "__selfcheck__", "trial", "active", "2026-01-01"),
        ).lastrowid
        print(f"insert returned id: {rid}  (must not be None)")
        c.execute("DELETE FROM orgs WHERE slug = ?", ("__selfcheck__",))
        c.commit()
        c.close()
        print("postgres path OK")
