def verify_point(conn, org_id, point, provider, today=None, commit=True):
    """
    Re-check one contact point and write the result back with its provenance.

    Returns the change as a dict for the activity feed. A verification run that
    downgrades a number is a *useful* outcome — the rep did not waste the dial —
    so it is reported rather than quietly applied.
    """
    today = (today or date.today()).isoformat()
    kind = point["kind"]
    result = (provider.verify_email(point["value"]) if kind == "email"
              else provider.verify_phone(point["value"]))

    if result.get("status") is None:
        return {"changed": False, "note": result.get("method", "verification unavailable")}

    before = point["status"]
    conn.execute(
        """UPDATE contact_points
              SET status = ?, confidence = ?, method = ?, last_verified = ?,
                  fail_count = CASE WHEN ? = 'invalid' THEN fail_count + 1 ELSE 0 END
            WHERE id = ? AND org_id = ?""",
        (result["status"], result["confidence"], result["method"], today,
         result["status"], point["id"], org_id))
    if commit:
        conn.commit()
    return {"changed": before != result["status"], "from": before,
            "to": result["status"], "note": result["method"]}


def verify_contact(conn, org_id, contact_id, provider, today=None):
    """Re-verify every point on one contact. Returns a list of change dicts."""
    points = conn.execute(
        "SELECT * FROM contact_points WHERE org_id = ? AND contact_id = ?",
        (org_id, contact_id)).fetchall()
    out = []
    for p in points:
        change = verify_point(conn, org_id, p, provider, today, commit=False)
        change["value"] = p["value"]
        change["kind"] = p["kind"]
        out.append(change)
    conn.commit()
    return out


# Dispositions that say something about the *number* rather than the person.
_DIAL_VERDICT = {
    "bad_number": ("invalid", 0, "dialed — disconnected or unreachable"),
    "wrong_number": ("invalid", 5, "dialed — reached someone else"),
    "connected": ("verified", 95, "dialed — reached the contact"),
    "meeting_set": ("verified", 96, "dialed — reached the contact"),
    "callback": ("verified", 94, "dialed — reached the contact"),
    "not_interested": ("verified", 93, "dialed — reached the contact"),
    "voicemail": ("verified", 82, "dialed — their voicemail answered"),
}


def record_dial_result(conn, org_id, point_value, disposition, today=None, commit=True):
    """
    Feed a call outcome back into the data layer.

    This is the loop that makes the platform's data get better the more it is
    used, and it costs nothing — the call was being made anyway. A vendor sells
    you a verification; a connect *is* one, and it is fresher than anything
    purchasable because it happened four minutes ago.
    """
    verdict = _DIAL_VERDICT.get(disposition)
    if not verdict:
        return None
    status, confidence, method = verdict
    today = (today or date.today()).isoformat()

    row = conn.execute(
        "SELECT * FROM contact_points WHERE org_id = ? AND value = ?",
        (org_id, point_value)).fetchone()
    if row is None:
        return None

    if status == "invalid":
        fails = (row["fail_count"] or 0) + 1
        # Two independent failures is a coincidence; three is the number.
        final = "invalid" if fails >= 3 else row["status"]
        conn.execute(
            """UPDATE contact_points SET fail_count = ?, status = ?,
                      confidence = ?, method = ?, last_verified = ?
                WHERE id = ? AND org_id = ?""",
            (fails, final, max(0, (row["confidence"] or 50) - 30), method, today,
             row["id"], org_id))
    else:
        conn.execute(
            """UPDATE contact_points SET status = ?, confidence = ?, method = ?,
                      last_verified = ?, fail_count = 0, source = ?
                WHERE id = ? AND org_id = ?""",
            (status, confidence, method, today, "connected_call", row["id"], org_id))
    if commit:
        conn.commit()
    return {"point_id": row["id"], "status": status, "method": method}


