# The data-quality report
# ---------------------------------------------------------------------------

def data_quality(conn, org_id, today=None, ttl_days=DEFAULT_TTL_DAYS):
    """
    What this org's data is actually worth, in numbers a CFO recognizes.

    The headline is not "82% coverage" — every vendor claims a coverage number
    and none of them mean the same thing. It is the count of records a rep will
    dial this quarter that will not reach anybody, and the hours that costs.
    """
    today = today or date.today()

    points = conn.execute(
        "SELECT * FROM contact_points WHERE org_id = ?", (org_id,)).fetchall()
    contacts = conn.execute(
        "SELECT * FROM contacts WHERE org_id = ?", (org_id,)).fetchall()
    companies = conn.execute(
        "SELECT COUNT(*) AS n FROM companies WHERE org_id = ?", (org_id,)).fetchone()["n"]

    buckets = {k: 0 for k in ("verified", "probable", "guessed", "catch_all", "invalid")}
    stale, phones, emails = 0, 0, 0
    for p in points:
        eff = effective_status(p, today, ttl_days)
        buckets[eff] = buckets.get(eff, 0) + 1
        if p["status"] == "verified" and eff != "verified":
            stale += 1
        if p["kind"] == "email":
            emails += 1
        else:
            phones += 1

    with_phone = {p["contact_id"] for p in points if p["kind"] != "email"}
    with_dial = {p["contact_id"] for p in points
                 if p["kind"] in ("direct_dial", "mobile")
                 and effective_status(p, today, ttl_days) in ("verified", "probable")}
    with_email = {p["contact_id"] for p in points if p["kind"] == "email"}

    departed = sum(1 for c in contacts if c["status"] == "left_company")
    unknown_role = sum(1 for c in contacts if c["role_type"] == "unknown")

    total = len(points) or 1
    # Everything that will not reach a person: already-invalid points plus the
    # share of guessed ones that historically do not land.
    dead = buckets["invalid"] + int(buckets["guessed"] * 0.55)
    # Two minutes per dial, dial and log. Conservative, and it is the number a
    # sales VP will check against their own floor.
    wasted_hours = round(dead * 2 / 60, 1)

    return {
        "companies": companies,
        "contacts": len(contacts),
        "points": len(points),
        "phones": phones,
        "emails": emails,
        "buckets": buckets,
        "pct": {k: round(v / total * 100) for k, v in buckets.items()},
        "stale_verifications": stale,
        "contacts_with_phone": len(with_phone),
        "contacts_with_dialable": len(with_dial),
        "contacts_with_email": len(with_email),
        "reachable_pct": round(len(with_dial) / max(len(contacts), 1) * 100),
        "departed": departed,
        "unknown_role": unknown_role,
        "dead_records": dead,
        "wasted_hours": wasted_hours,
        "ttl_days": ttl_days,
    }


def worst_records(conn, org_id, limit=25, today=None, ttl_days=DEFAULT_TTL_DAYS):
    """
    The specific records to fix first, worst-cost-per-record at the top.

    A percentage on a dashboard does not get fixed. A list of forty names with a
    Re-verify button next to each does.
    """
    rows = conn.execute(
        """SELECT c.id, c.name, c.title, c.status, c.role_started, c.last_verified,
                  co.name AS company, co.id AS company_id,
                  (SELECT COUNT(*) FROM targets t WHERE t.contact_id = c.id) AS targeted
             FROM contacts c JOIN companies co ON co.id = c.company_id
            WHERE c.org_id = ?""", (org_id,)).fetchall()

    points = {}
    for p in conn.execute("SELECT * FROM contact_points WHERE org_id = ?",
                          (org_id,)).fetchall():
        points.setdefault(p["contact_id"], []).append(p)

    scored = []
    for c in rows:
        pts = points.get(c["id"], [])
        problems = []
        cost = 0
        if c["status"] == "left_company":
            problems.append("has left the company")
            cost += 50
        dialable = [p for p in pts if p["kind"] in ("direct_dial", "mobile")]
        if not dialable:
            problems.append("no direct number")
            cost += 30
        for p in pts:
            eff = effective_status(p, today, ttl_days)
            if eff == "invalid":
                problems.append(f"{p['kind'].replace('_', ' ')} is dead")
                cost += 25
            elif p["status"] == "guessed":
                problems.append(f"{p['kind'].replace('_', ' ')} is a guess")
                cost += 12
            elif p["status"] == "verified" and eff != "verified":
                problems.append(f"{p['kind'].replace('_', ' ')} verification expired")
                cost += 10
        if not problems:
            continue
        # A broken record on an account nobody is working costs nothing. Weight
        # by whether a rep is going to hit it.
        cost *= 1 + min(c["targeted"], 3)
        scored.append({"contact": c, "problems": problems, "cost": cost,
                       "points": pts})

    scored.sort(key=lambda r: -r["cost"])
    return scored[:limit]
