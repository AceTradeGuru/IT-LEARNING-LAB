"""
Royal Grind — where contact data comes from, and how much of it to believe.

The source document behind this product rates "accurate contact information" a
9/10 and "keeping data continuously updated" a 10/10, and it is right. Version 1
does not solve that by out-collecting ZoomInfo. It solves the part that is
actually tractable: **being honest about which fields are trustworthy, and
turning the org's own dialing into a verification stream nobody else has.**

Three ideas carry the module.

**1. Every field is a claim with a source and an expiry.** `contact_points` rows
carry `status`, `source`, `method`, `last_verified` and `confidence`. A rep
looking at a number sees whether it was confirmed, how, and when. A platform
that renders a verified direct dial and a pattern-guessed one in the same black
text is lying by omission, and the rep finds out one dial at a time.

**2. Confidence decays.** A number verified in March is not verified in
September; roughly a fifth of B2B contacts change role in a year. `decayed()`
computes present-day confidence from the verification date, so a record that
nobody re-checks slides toward "probable" on its own rather than sitting at 95%
forever.

**3. The dialer is the best verification service in the building.** When a call
comes back `bad_number`, that is a harder signal than any vendor's API — the
org paid for it and it is first-party. `record_dial_result()` writes it back to
the point, and three failures retire the number. Over a quarter this is the
proprietary data asset the strategy document is pointing at: not more contacts,
but better-verified ones on the accounts this org actually calls.

**Providers.** `OfflineProvider` is deterministic and labels everything it
produces as simulated — it makes the repo clone and demo without an account and
without ever claiming a number is real. `HttpProvider` is the shape a licensed
vendor plugs into; point it at one and every downstream consumer keeps working,
because they all read `status` and `confidence` rather than the vendor's name.

> **Testing status.** `OfflineProvider` is exercised by the smoke test.
> `HttpProvider` is written against a generic REST contract and has not been run
> against a commercial vendor — there is no data contract attached to this
> repository. Wiring a real provider means confirming its response shape and
> mapping it in `HttpProvider._map()`, and reading its license terms about what
> you may store and for how long.
"""

import hashlib
import json
import re
import urllib.error
import urllib.request
from datetime import date, datetime, timedelta

# How far to trust a field purely on where it came from, before verification.
# Ordering matters more than the exact numbers: a number the prospect themselves
# said out loud on a call outranks anything a vendor sells.
SOURCE_TRUST = {
    "self_reported": 96,     # they gave it to us on a call
    "connected_call": 92,    # we dialed it and a human answered
    "customer_crm": 84,      # imported from the customer's own CRM
    "vendor_verified": 78,   # a licensed provider that claims verification
    "website": 70,           # scraped from the company's own site
    "vendor": 58,            # a licensed provider, unverified tier
    "public_filing": 66,
    "manual": 55,            # a rep typed it in
    "pattern": 34,           # constructed from a naming convention
    "offline_demo": 50,      # generated by the demo seed; never real
}

# Verification does not last. This is roughly the observed annual B2B contact
# churn spread across a year, and it is deliberately conservative.
DEFAULT_TTL_DAYS = 90

STATUS_LABELS = {
    "verified": "Verified",
    "probable": "Probable",
    "guessed": "Guessed",
    "catch_all": "Catch-all domain",
    "invalid": "Invalid",
}


# ---------------------------------------------------------------------------
# Confidence over time
# ---------------------------------------------------------------------------

def decayed(confidence, last_verified, today=None, ttl_days=DEFAULT_TTL_DAYS):
    """
    Present-day confidence in a field verified on `last_verified`.

    Linear to the TTL, then a slow tail — not a cliff. A number checked 91 days
    ago is not suddenly worthless, and a decay function with a step in it makes
    the data-quality dashboard jump for reasons nobody can explain.
    """
    if confidence is None:
        return 0
    if not last_verified:
        return int(confidence * 0.75)
    today = today or date.today()
    try:
        when = datetime.strptime(str(last_verified)[:10], "%Y-%m-%d").date()
    except ValueError:
        return int(confidence * 0.75)
    age = max((today - when).days, 0)
    if age <= ttl_days:
        factor = 1.0 - 0.35 * (age / ttl_days)
    else:
        over = age - ttl_days
        factor = max(0.2, 0.65 - 0.25 * (over / ttl_days))
    return int(round(confidence * factor))


def effective_status(point, today=None, ttl_days=DEFAULT_TTL_DAYS):
    """
    What the status *is today*, as opposed to what was written when it was set.

    A point marked verified whose verification has aged out reports as probable.
    The stored row is not rewritten — the history of what was known when is worth
    keeping — so this is computed on read.
    """
    status = point["status"]
    if status != "verified":
        return status
    conf = decayed(point["confidence"], point["last_verified"], today, ttl_days)
    return "verified" if conf >= 60 else "probable"


