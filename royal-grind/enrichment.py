class Provider:
    name = "abstract"

    def verify_phone(self, number, company=None):
        raise NotImplementedError

    def verify_email(self, address, company=None):
        raise NotImplementedError

    def status(self):
        return {"provider": self.name, "live": False, "detail": ""}


class OfflineProvider(Provider):
    """
    Deterministic pseudo-verification for local development and demos.

    It does not contact anything. The result is a hash of the value, so the same
    number always verifies the same way and a demo is reproducible. Every field
    it touches is stamped `method="offline simulation"` and the UI renders that
    string, because a fake verification presented as a real one is the single
    most damaging thing this module could do.
    """

    name = "offline"

    def status(self):
        return {"provider": "offline", "live": False,
                "detail": ("Verification is simulated — no data provider is connected. "
                           "Every result is labelled as such. Set ENRICHMENT_PROVIDER "
                           "and ENRICHMENT_API_KEY to verify against a real service.")}

    def _roll(self, value, salt=""):
        h = hashlib.sha256(f"{salt}:{value}".encode()).hexdigest()
        return int(h[:8], 16) / 0xFFFFFFFF

    def verify_phone(self, number, company=None):
        digits = re.sub(r"\D", "", number or "")
        if len(digits) < 10:
            return {"status": "invalid", "confidence": 0,
                    "method": "offline simulation — not a dialable number"}
        r = self._roll(digits, "phone")
        if r < 0.62:
            return {"status": "verified", "confidence": 88,
                    "method": "offline simulation — line active, name matched"}
        if r < 0.88:
            return {"status": "probable", "confidence": 58,
                    "method": "offline simulation — line active, name not matched"}
        return {"status": "invalid", "confidence": 5,
                "method": "offline simulation — disconnected"}

    def verify_email(self, address, company=None):
        address = (address or "").strip().lower()
        if "@" not in address:
            return {"status": "invalid", "confidence": 0,
                    "method": "offline simulation — malformed"}
        r = self._roll(address, "email")
        if r < 0.55:
            return {"status": "verified", "confidence": 90,
                    "method": "offline simulation — mailbox accepted"}
        if r < 0.72:
            return {"status": "catch_all", "confidence": 40,
                    "method": "offline simulation — domain accepts all mail"}
        if r < 0.9:
            return {"status": "probable", "confidence": 55,
                    "method": "offline simulation — no definitive answer"}
        return {"status": "invalid", "confidence": 3,
                "method": "offline simulation — mailbox rejected"}


class HttpProvider(Provider):
    """
    A licensed verification vendor, behind the same two methods.

    The contract assumed is a POST to `{base}/verify/{phone|email}` with a bearer
    token, returning `{"result": "valid"|"invalid"|"catch_all"|"unknown",
    "confidence": 0-100, "method": "..."}`. Real vendors differ; `_map()` is the
    one function to change, and nothing downstream cares.

    Failure is not fatal and is not silent. A vendor outage leaves the field at
    whatever it was and records that the check did not happen, rather than
    marking a good number invalid because an API returned 503.
    """

    name = "http"

    def __init__(self, base_url, api_key, timeout=10):
        self.base_url = (base_url or "").rstrip("/")
        self.api_key = api_key
        self.timeout = timeout

    def status(self):
        ready = bool(self.base_url and self.api_key)
        return {"provider": "http", "live": ready,
                "detail": ("Live verification provider." if ready else
                           "ENRICHMENT_API_KEY is not set.")}

    def _post(self, path, body):
        req = urllib.request.Request(
            f"{self.base_url}{path}", data=json.dumps(body).encode(), method="POST",
            headers={"Authorization": f"Bearer {self.api_key}",
                     "Content-Type": "application/json"})
        with urllib.request.urlopen(req, timeout=self.timeout) as resp:
            return json.loads(resp.read().decode() or "{}")

    @staticmethod
    def _map(payload, kind):
        result = (payload.get("result") or "unknown").lower()
        confidence = int(payload.get("confidence") or 0)
        method = payload.get("method") or f"{kind} verification provider"
        if result == "valid":
            return {"status": "verified", "confidence": max(confidence, 80), "method": method}
        if result == "catch_all":
            return {"status": "catch_all", "confidence": min(confidence, 45), "method": method}
        if result == "invalid":
            return {"status": "invalid", "confidence": 0, "method": method}
        return {"status": "probable", "confidence": confidence or 50, "method": method}

    def verify_phone(self, number, company=None):
        try:
            return self._map(self._post("/verify/phone", {"number": number}), "phone")
        except (urllib.error.URLError, ValueError, KeyError) as exc:
            return {"status": None, "confidence": None,
                    "method": f"verification unavailable ({exc.__class__.__name__})"}

    def verify_email(self, address, company=None):
        try:
            return self._map(self._post("/verify/email", {"address": address}), "email")
        except (urllib.error.URLError, ValueError, KeyError) as exc:
            return {"status": None, "confidence": None,
                    "method": f"verification unavailable ({exc.__class__.__name__})"}


def get_provider(config):
    """One place decides which verification service is live. See config.py."""
    if (config.ENRICHMENT_PROVIDER or "offline").lower() == "http":
        return HttpProvider(config.ENRICHMENT_PROVIDER_URL, config.ENRICHMENT_API_KEY)
    return OfflineProvider()


